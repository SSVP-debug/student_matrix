import { useRef, useState } from 'react';
import { useNavigate } from 'react-router-dom';
import { Upload, Trash2, Loader2, Target } from 'lucide-react';
import { Page, Card, btnPrimary, btnGhost } from '../components/Page';
import { updateProfile, useProfile } from '../engine/store';
import { buildNote, extractText } from '../engine/notes';
import type { Note } from '../engine/types';

export const LearnHub = () => {
  const nav = useNavigate();
  const p = useProfile();
  const [title, setTitle] = useState('');
  const [text, setText] = useState('');
  const [busy, setBusy] = useState(false);
  const [msg, setMsg] = useState('');
  const [open, setOpen] = useState<string | null>(null);
  const file = useRef<HTMLInputElement>(null);

  const add = (t: string, name: string) => {
    if (t.trim().length < 200) { setMsg('Please provide at least a few paragraphs of text (200+ characters).'); return; }
    const note = buildNote(name, t);
    updateProfile((pp) => ({ ...pp, notes: [note, ...pp.notes].slice(0, 30) }));
    setTitle(''); setText(''); setOpen(note.id);
    setMsg(`Saved "${note.title}": ${note.summary.length} summary points, ${note.questions.length} questions, ${note.cards.length} flashcards. All generated on this device.`);
  };

  const onFile = async (f: File | undefined) => {
    if (!f) return;
    setBusy(true); setMsg('');
    try {
      if (f.size > 15 * 1024 * 1024) throw new Error('File is larger than 15 MB.');
      add(await extractText(f), title || f.name.replace(/\.[^.]+$/, ''));
    } catch (e) { setMsg(`Could not read the file: ${(e as Error).message}`); }
    finally { setBusy(false); if (file.current) file.current.value = ''; }
  };

  const remove = (n: Note) => { if (confirm(`Delete "${n.title}" and its generated questions and flashcards?`)) updateProfile((pp) => ({ ...pp, notes: pp.notes.filter((x) => x.id !== n.id) })); };

  return (
    <Page title="My Notes" subtitle="Turn text or PDFs into summaries, flashcards and practice questions — processed locally, nothing is uploaded.">
      <div className="grid lg:grid-cols-2 gap-4">
        <Card className="space-y-3">
          <label htmlFor="title" className="block text-sm text-white/70">Title</label>
          <input id="title" value={title} onChange={(e) => setTitle(e.target.value)} placeholder="e.g. Photosynthesis chapter" className="w-full rounded-2xl bg-[#080910] border border-white/15 focus:border-cyan-300/40 focus:ring-2 focus:ring-cyan-300/10 p-3" />
          <label htmlFor="text" className="block text-sm text-white/70">Paste text</label>
          <textarea id="text" value={text} onChange={(e) => setText(e.target.value)} rows={9} placeholder="Paste your notes or textbook passage here…" className="w-full rounded-2xl bg-[#080910] border border-white/15 focus:border-cyan-300/40 focus:ring-2 focus:ring-cyan-300/10 p-3" />
          <div className="flex flex-wrap gap-3">
            <button className={btnPrimary} disabled={busy || !text.trim()} onClick={() => add(text, title)}>Create study material</button>
            <input ref={file} type="file" accept=".pdf,.txt,.md,text/plain,application/pdf" className="hidden" id="upload" onChange={(e) => onFile(e.target.files?.[0])} />
            <button className={btnGhost} disabled={busy} onClick={() => file.current?.click()}>{busy ? <Loader2 className="inline w-4 h-4 animate-spin" aria-hidden /> : <Upload className="inline w-4 h-4 mr-1" aria-hidden />} Upload PDF / TXT</button>
          </div>
          {msg && <p role="status" className="text-sm text-white/80">{msg}</p>}
          <p className="text-xs text-white/60">Summaries and questions are generated by simple on-device language rules, so they are a starting point — skim them before relying on them. PDFs are limited to the first 40 pages.</p>
        </Card>

        <div className="space-y-3">
          {p.notes.length === 0 && <Card><p className="text-white/70">No notes yet. Add some text and your tutor, flashcards and practice sessions will use it too.</p></Card>}
          {p.notes.map((n) => (
            <Card key={n.id}>
              <div className="flex items-start justify-between gap-3">
                <button className="text-left" aria-expanded={open === n.id} onClick={() => setOpen(open === n.id ? null : n.id)}>
                  <p className="font-semibold">{n.title}</p>
                  <p className="text-xs text-white/70">{n.questions.length} questions · {n.cards.length} flashcards · {new Date(n.createdAt).toLocaleDateString()}</p>
                </button>
                <div className="flex gap-2">
                  {n.questions.length > 0 && <button aria-label={`Practise ${n.title}`} className={btnGhost} onClick={() => nav(`/quests?topic=${encodeURIComponent(`My notes: ${n.title}`)}`)}><Target className="w-4 h-4" /></button>}
                  <button aria-label={`Delete ${n.title}`} className={btnGhost} onClick={() => remove(n)}><Trash2 className="w-4 h-4" /></button>
                </div>
              </div>
              {open === n.id && (
                <div className="mt-3 space-y-3 text-sm text-white/85">
                  <div><p className="font-medium text-white mb-1">Summary</p><ul className="list-disc pl-5 space-y-1">{n.summary.map((s, i) => <li key={i}>{s}</li>)}</ul></div>
                  {n.keyTerms.length > 0 && <div><p className="font-medium text-white mb-1">Key terms</p><p>{n.keyTerms.join(' · ')}</p></div>}
                </div>
              )}
            </Card>
          ))}
        </div>
      </div>
    </Page>
  );
};
